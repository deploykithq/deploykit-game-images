#!/usr/bin/env bash
# The game files live in /server, which is never backed up; the operator's
# config lives in /data/cfg and is linked into the game's cfg directory.
#   /data/cfg/*.cfg     the user's files (server.cfg, gamemode_*_server.cfg…)
#   dk_server.cfg       generated every start from DK_VAR_*; not user-editable
. /opt/deploykit/lib/common.sh

game_cfg=$DK_SERVER_DIR/cs2/game/csgo/cfg
user_cfg=$DK_DATA_DIR/cfg
mkdir -p "$user_cfg" "$game_cfg"

if [[ ! -f $user_cfg/server.cfg ]]; then
    cat >"$user_cfg/server.cfg" <<'EOF'
// Your own cvars. Executed by CS2 on every map load.
// Per-mode settings go in gamemode_competitive_server.cfg, gamemode_casual_server.cfg…
EOF
fi

# Link the user's files in; drop links to files the user has deleted.
find "$game_cfg" -maxdepth 1 -type l -lname "$user_cfg/*" ! -exec test -e {} \; -delete
for f in "$user_cfg"/*.cfg; do
    [[ -f $f ]] && ln -sfn "$f" "$game_cfg/$(basename "$f")"
done

name=${DK_VAR_SERVER_NAME:-DeployKit CS2}
# The name lands inside a quoted cvar: refuse what could break out of it.
unsafe='["'"'"'`$&/\\]'
if ((${#name} < 1 || ${#name} > 63)) || [[ $name =~ $unsafe || $name == *$'\n'* ]]; then
    dk_die "DK_VAR_SERVER_NAME: 1-63 characters, no quotes, slashes, \$, & or backticks"
fi
pw=${DK_VAR_SERVER_PASSWORD:-}
[[ -z $pw || $pw =~ ^[A-Za-z0-9_-]{1,64}$ ]] || dk_die "DK_VAR_SERVER_PASSWORD: letters, digits, - and _ only"

# CS2 serves RCON on the game port's TCP side, on every interface. The
# generated password is never shown to anyone, so only brute force could get
# in: ban an address after a few failures. A rcon_password in the user's own
# files (executed on every map load) would replace it.
if grep -lis '^[[:space:]]*rcon_password' "$user_cfg"/*.cfg 2>/dev/null; then
    dk_log "warning: the files above set rcon_password; it replaces the generated one and breaks the console"
fi

umask 077
cat >"$game_cfg/dk_server.cfg" <<EOF
// Generated by DeployKit on every start. Edit /data/cfg/server.cfg instead.
hostname "$name"
sv_password "$pw"
rcon_password "${DK_RCON_PASSWORD:?}"
sv_rcon_maxfailures 5
sv_rcon_banpenalty 60
EOF
